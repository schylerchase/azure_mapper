import { _extractTags, _bicepEsc, _proto, _nsgSelectors, _natPublicIps, _subnetNatId, _selectIacData, _iacExportBlock } from "./iac-resource-formatters.js";

// ============================================================
// 3. BICEP GENERATION
// ============================================================

export function generateBicep(data, options) {
  if (!data) return { code: '// No data loaded', warnings: [], stats: {} };
  const opts = options || {};
  data = _selectIacData(data, opts);
  const blocked = _iacExportBlock(data, 'bicep');
  if (blocked) return blocked;
  const lines = [];
  const warnings = [];
  const quote = value => "'" + _bicepEsc(value) + "'";

  const vnets = data.vnets || [];
  const nsgs = (data.nsgs || []).concat(data.subnetNsgs || []);
  const udrs = data.udrs || [];
  const natGateways = data.natGateways || [];
  const vms = data.vms || [];
  const nics = data.nics || [];
  const disks = data.disks || [];
  const peerings = data.peerings || [];
  const firewalls = data.firewalls || [];
  const bastions = data.bastions || [];

  // Deduplicate NSGs
  const nsgMap = new Map();
  nsgs.forEach(n => { if (n.id) nsgMap.set(n.id.toLowerCase(), n); });
  const uniqueNsgs = Array.from(nsgMap.values());

  // Bicep symbol name tracker to avoid collisions
  const symSeen = new Set();
  function _bsym(raw, prefix) {
    let base = (raw || prefix || 'res').replace(/[^a-zA-Z0-9_]/g, '_').replace(/^[0-9]/, 'r$&');
    // Bicep identifiers are camelCase by convention
    base = base.charAt(0).toLowerCase() + base.slice(1);
    let sym = base, i = 2;
    while (symSeen.has(sym)) { sym = base + i; i++; }
    symSeen.add(sym);
    return sym;
  }

  // Map resource id -> bicep symbol for references
  const bicepIdMap = {};

  // --- Header ---
  lines.push('// Generated by Azure Mapper');
  lines.push('// Date: ' + new Date().toISOString().split('T')[0]);
  lines.push('');

  // --- Parameters ---
  lines.push('param location string = ' + (vnets[0]?.location ? quote(vnets[0].location) : 'resourceGroup().location'));
  lines.push('param adminUsername string = \'azureadmin\'');
  lines.push('@secure()');
  lines.push('param adminPassword string');
  lines.push('');

  // Helper: write Bicep tags
  function _bicepTags(resource, indent) {
    const tags = _extractTags(resource);
    const keys = Object.keys(tags);
    if (!keys.length) return;
    const pad = '  '.repeat(indent);
    lines.push(pad + 'tags: {');
    keys.forEach(k => {
      const safeKey = k.match(/^[a-zA-Z_][a-zA-Z0-9_]*$/) ? k : quote(k);
      lines.push(pad + '  ' + safeKey + ': ' + quote(tags[k]));
    });
    lines.push(pad + '}');
  }

  // --- NSGs ---
  uniqueNsgs.forEach(nsg => {
    const sym = _bsym(nsg.name, 'nsg');
    bicepIdMap[(nsg.id || '').toLowerCase()] = sym;
    lines.push('resource ' + sym + ' \'Microsoft.Network/networkSecurityGroups@2023-04-01\' = {');
    lines.push('  name: ' + quote(nsg.name || 'nsg'));
    lines.push('  location: location');
    _bicepTags(nsg, 1);
    lines.push('  properties: {');
    const rules = (nsg.properties || nsg).securityRules || [];
    if (rules.length) {
      lines.push('    securityRules: [');
      rules.forEach(rule => {
        const rp = rule.properties || rule;
        lines.push('      {');
        lines.push('        name: ' + quote(rule.name || 'rule'));
        lines.push('        properties: {');
        lines.push('          priority: ' + (rp.priority || 100));
        lines.push('          direction: ' + quote(rp.direction || 'Inbound'));
        lines.push('          access: ' + quote(rp.access || 'Allow'));
        lines.push('          protocol: ' + quote(_proto(rp.protocol)));
        for (const [key, selector] of Object.entries(_nsgSelectors(rp))) {
          if (Array.isArray(selector)) {
            lines.push('          ' + key + ': [');
            selector.forEach(item => lines.push('            ' + (typeof item === 'object' ? '{ id: ' + quote(item.id) + ' }' : quote(item))));
            lines.push('          ]');
          } else lines.push('          ' + key + ': ' + quote(selector));
        }
        lines.push('        }');
        lines.push('      }');
      });
      lines.push('    ]');
    } else {
      lines.push('    securityRules: []');
    }
    lines.push('  }');
    lines.push('}');
    lines.push('');
  });

  // --- Route Tables ---
  udrs.forEach(udr => {
    const sym = _bsym(udr.name, 'rt');
    bicepIdMap[(udr.id || '').toLowerCase()] = sym;
    lines.push('resource ' + sym + ' \'Microsoft.Network/routeTables@2023-04-01\' = {');
    lines.push('  name: ' + quote(udr.name || 'rt'));
    lines.push('  location: location');
    _bicepTags(udr, 1);
    lines.push('  properties: {');
    if ((udr.properties || udr).disableBgpRoutePropagation) {
      lines.push('    disableBgpRoutePropagation: true');
    }
    const routes = (udr.properties || udr).routes || [];
    if (routes.length) {
      lines.push('    routes: [');
      routes.forEach(route => {
        const rp = route.properties || route;
        lines.push('      {');
        lines.push('        name: ' + quote(route.name || 'route'));
        lines.push('        properties: {');
        lines.push('          addressPrefix: ' + quote(rp.addressPrefix || '0.0.0.0/0'));
        lines.push('          nextHopType: ' + quote(rp.nextHopType || 'None'));
        if (rp.nextHopIpAddress) {
          lines.push('          nextHopIpAddress: ' + quote(rp.nextHopIpAddress));
        }
        lines.push('        }');
        lines.push('      }');
      });
      lines.push('    ]');
    } else {
      lines.push('    routes: []');
    }
    lines.push('  }');
    lines.push('}');
    lines.push('');
  });

  // --- NAT Public IPs and Gateways ---
  _natPublicIps(data).forEach(pip => {
    const sym = _bsym(pip.name || pip.id.split('/').pop(), 'pip');
    bicepIdMap[pip.id.toLowerCase()] = sym;
    lines.push('resource ' + sym + ' \'Microsoft.Network/publicIPAddresses@2023-04-01\' = {');
    lines.push('  name: ' + quote(pip.name || pip.id.split('/').pop()));
    lines.push('  location: location');
    lines.push('  sku: { name: ' + quote(pip.sku?.name || 'Standard') + ' }');
    _bicepTags(pip, 1);
    lines.push('  properties: { publicIPAllocationMethod: ' + quote((pip.properties || pip).publicIPAllocationMethod || 'Static') + ' }');
    lines.push('}');
    lines.push('');
  });
  natGateways.forEach(nat => {
    const sym = _bsym(nat.name, 'natGw');
    bicepIdMap[(nat.id || '').toLowerCase()] = sym;
    const np = nat.properties || nat;
    lines.push('resource ' + sym + ' \'Microsoft.Network/natGateways@2023-04-01\' = {');
    lines.push('  name: ' + quote(nat.name || 'natgw'));
    lines.push('  location: location');
    lines.push('  sku: {');
    lines.push('    name: ' + quote(nat.sku?.name || 'Standard'));
    lines.push('  }');
    _bicepTags(nat, 1);
    lines.push('  properties: {');
    lines.push('    idleTimeoutInMinutes: ' + (np.idleTimeoutInMinutes || 4));
    if (np.publicIpAddresses?.length) {
      lines.push('    publicIpAddresses: [');
      np.publicIpAddresses.filter(pip => pip.id).forEach(pip => lines.push('      { id: ' + bicepIdMap[pip.id.toLowerCase()] + '.id }'));
      lines.push('    ]');
    }
    if (np.publicIpPrefixes?.length) {
      lines.push('    publicIpPrefixes: [');
      np.publicIpPrefixes.filter(prefix => prefix.id).forEach(prefix => lines.push('      { id: ' + quote(prefix.id) + ' }'));
      lines.push('    ]');
    }
    lines.push('  }');
    lines.push('}');
    lines.push('');
  });

  // --- Virtual Networks ---
  vnets.forEach(vnet => {
    const sym = _bsym(vnet.name, 'vnet');
    bicepIdMap[(vnet.id || '').toLowerCase()] = sym;
    const addrSpace = (vnet.properties || vnet).addressSpace?.addressPrefixes || ['10.0.0.0/16'];
    lines.push('resource ' + sym + ' \'Microsoft.Network/virtualNetworks@2023-04-01\'' + (vnet._iacExistingParent ? ' existing' : '') + ' = {');
    lines.push('  name: ' + quote(vnet.name || 'vnet'));
    if (!vnet._iacExistingParent) {
      lines.push('  location: location');
      _bicepTags(vnet, 1);
      lines.push('  properties: {');
      lines.push('    addressSpace: {');
      lines.push('      addressPrefixes: [');
      addrSpace.forEach(a => lines.push('        ' + quote(a)));
      lines.push('      ]');
      lines.push('    }');
      const dnsServers = (vnet.properties || vnet).dhcpOptions?.dnsServers || [];
      if (dnsServers.length) {
        lines.push('    dhcpOptions: {');
        lines.push('      dnsServers: [');
        dnsServers.forEach(d => lines.push('        ' + quote(d)));
        lines.push('      ]');
        lines.push('    }');
      }
      lines.push('  }');
    }
    lines.push('}');
    lines.push('');

    // Subnets as child resources
    ((vnet.properties || vnet).subnets || []).forEach(sub => {
      const subSym = _bsym(sub.name, 'subnet');
      bicepIdMap[(sub.id || '').toLowerCase()] = subSym;
      const sp = sub.properties || sub;
      lines.push('resource ' + subSym + ' \'Microsoft.Network/virtualNetworks/subnets@2023-04-01\' = {');
      lines.push('  parent: ' + sym);
      lines.push('  name: ' + quote(sub.name || 'subnet'));
      lines.push('  properties: {');
      if (sp.addressPrefixes?.length) {
        lines.push('    addressPrefixes: [');
        sp.addressPrefixes.forEach(prefix => lines.push('      ' + quote(prefix)));
        lines.push('    ]');
      } else lines.push('    addressPrefix: ' + quote(sp.addressPrefix || '10.0.0.0/24'));
      const natId = _subnetNatId(sub, natGateways);
      if (natId) lines.push('    natGateway: { id: ' + (bicepIdMap[natId.toLowerCase()] ? bicepIdMap[natId.toLowerCase()] + '.id' : quote(natId)) + ' }');
      // NSG reference
      const nsgId = sp.networkSecurityGroup?.id;
      if (nsgId) {
        const nsgSym = bicepIdMap[nsgId.toLowerCase()];
        if (nsgSym) {
          lines.push('    networkSecurityGroup: {');
          lines.push('      id: ' + nsgSym + '.id');
          lines.push('    }');
        } else lines.push('    networkSecurityGroup: { id: ' + quote(nsgId) + ' }');
      }
      // Route table reference
      const rtId = sp.routeTable?.id;
      if (rtId) {
        const rtSym = bicepIdMap[rtId.toLowerCase()];
        if (rtSym) {
          lines.push('    routeTable: {');
          lines.push('      id: ' + rtSym + '.id');
          lines.push('    }');
        } else lines.push('    routeTable: { id: ' + quote(rtId) + ' }');
      }
      // Service endpoints
      const svcEndpoints = sp.serviceEndpoints || [];
      if (svcEndpoints.length) {
        lines.push('    serviceEndpoints: [');
        svcEndpoints.forEach(se => {
          lines.push('      {');
          lines.push('        service: ' + quote(se.service));
          lines.push('      }');
        });
        lines.push('    ]');
      }
      // Delegations
      const delegations = sp.delegations || [];
      if (delegations.length) {
        lines.push('    delegations: [');
        delegations.forEach(d => {
          lines.push('      {');
          lines.push('        name: ' + quote(d.name || 'delegation'));
          lines.push('        properties: {');
          lines.push('          serviceName: ' + quote(d.properties?.serviceName));
          lines.push('        }');
          lines.push('      }');
        });
        lines.push('    ]');
      }
      lines.push('  }');
      lines.push('}');
      lines.push('');
    });
  });

  // --- NICs ---
  nics.forEach(nic => {
    const sym = _bsym(nic.name, 'nic');
    bicepIdMap[(nic.id || '').toLowerCase()] = sym;
    lines.push('resource ' + sym + ' \'Microsoft.Network/networkInterfaces@2023-04-01\' = {');
    lines.push('  name: ' + quote(nic.name || 'nic'));
    lines.push('  location: location');
    _bicepTags(nic, 1);
    lines.push('  properties: {');
    const np = nic.properties || nic;
    const nsgId = np.networkSecurityGroup?.id;
    if (nsgId) lines.push('    networkSecurityGroup: { id: ' + (bicepIdMap[nsgId.toLowerCase()] ? bicepIdMap[nsgId.toLowerCase()] + '.id' : quote(nsgId)) + ' }');
    const ipConfigs = np.ipConfigurations || [];
    lines.push('    ipConfigurations: [');
    ipConfigs.forEach(ipc => {
      const ipcProps = ipc.properties || ipc;
      lines.push('      {');
      lines.push('        name: ' + quote(ipc.name || 'ipconfig'));
      lines.push('        properties: {');
      lines.push('          privateIPAllocationMethod: ' + quote(ipcProps.privateIPAllocationMethod || 'Dynamic'));
      if (ipcProps.privateIPAddressVersion) lines.push('          privateIPAddressVersion: ' + quote(ipcProps.privateIPAddressVersion));
      if (typeof ipcProps.primary === 'boolean') lines.push('          primary: ' + ipcProps.primary);
      if (ipcProps.publicIPAddress?.id) lines.push('          publicIPAddress: { id: ' + quote(ipcProps.publicIPAddress.id) + ' }');
      const subId = ipcProps.subnet?.id;
      if (subId) {
        const subSym = bicepIdMap[subId.toLowerCase()];
        if (subSym) {
          lines.push('          subnet: {');
          lines.push('            id: ' + subSym + '.id');
          lines.push('          }');
        } else lines.push('          subnet: { id: ' + quote(subId) + ' }');
      }
      if (ipcProps.privateIPAddress && ipcProps.privateIPAllocationMethod === 'Static') {
        lines.push('          privateIPAddress: ' + quote(ipcProps.privateIPAddress));
      }
      lines.push('        }');
      lines.push('      }');
    });
    lines.push('    ]');
    lines.push('  }');
    lines.push('}');
    lines.push('');
  });

  const diskSymbols = new Map();
  disks.forEach(disk => {
    const sym = _bsym(disk.name, 'disk');
    diskSymbols.set(disk, sym);
    if (disk.id) bicepIdMap[disk.id.toLowerCase()] = sym;
  });

  // --- Virtual Machines ---
  vms.forEach(vm => {
    const sym = _bsym(vm.name, 'vm');
    const vmp = vm.properties || vm;
    const osProfile = vmp.osProfile || {};
    const isWindows = !!(osProfile.windowsConfiguration || (vmp.storageProfile?.osDisk?.osType || '').toLowerCase() === 'windows');
    const imgRef = vmp.storageProfile?.imageReference || {};
    const osDisk = vmp.storageProfile?.osDisk || {};
    const attachedOs = String(osDisk.createOption || '').toLowerCase() === 'attach';

    lines.push('resource ' + sym + ' \'Microsoft.Compute/virtualMachines@2023-07-01\' = {');
    lines.push('  name: ' + quote(vm.name || 'vm'));
    lines.push('  location: location');
    _bicepTags(vm, 1);
    lines.push('  properties: {');
    lines.push('    hardwareProfile: {');
    lines.push('      vmSize: ' + quote(vmp.hardwareProfile?.vmSize || 'Standard_B2s'));
    lines.push('    }');
    lines.push('    storageProfile: {');
    if (!attachedOs) {
      lines.push('      imageReference: {');
      if (imgRef.id) lines.push('        id: ' + quote(imgRef.id));
      else {
        lines.push('        publisher: ' + quote(imgRef.publisher || (isWindows ? 'MicrosoftWindowsServer' : 'Canonical')));
        lines.push('        offer: ' + quote(imgRef.offer || (isWindows ? 'WindowsServer' : '0001-com-ubuntu-server-jammy')));
        lines.push('        sku: ' + quote(imgRef.sku || (isWindows ? '2022-datacenter-g2' : '22_04-lts-gen2')));
        lines.push('        version: ' + quote(imgRef.version || 'latest'));
      }
      lines.push('      }');
    }
    lines.push('      osDisk: {');
    lines.push('        createOption: ' + quote(attachedOs ? 'Attach' : osDisk.createOption || 'FromImage'));
    if (attachedOs) {
      if (osDisk.name) lines.push('        name: ' + quote(osDisk.name));
      if (osDisk.osType) lines.push('        osType: ' + quote(osDisk.osType));
      if (osDisk.caching) lines.push('        caching: ' + quote(osDisk.caching));
    }
    lines.push('        managedDisk: {');
    if (attachedOs) lines.push('          id: ' + quote(osDisk.managedDisk.id));
    if (osDisk.managedDisk?.storageAccountType || !attachedOs) lines.push('          storageAccountType: ' + quote(osDisk.managedDisk?.storageAccountType || 'Standard_LRS'));
    if (attachedOs && osDisk.managedDisk?.diskEncryptionSet?.id) lines.push('          diskEncryptionSet: { id: ' + quote(osDisk.managedDisk.diskEncryptionSet.id) + ' }');
    lines.push('        }');
    if (osDisk.diskSizeGB) lines.push('        diskSizeGB: ' + osDisk.diskSizeGB);
    lines.push('      }');
    const dataDisks = vmp.storageProfile?.dataDisks || [];
    if (dataDisks.length) {
      lines.push('      dataDisks: [');
      dataDisks.forEach(disk => {
        lines.push('        {');
        if (disk.name) lines.push('          name: ' + quote(disk.name));
        lines.push('          lun: ' + disk.lun);
        lines.push('          createOption: ' + quote(disk.managedDisk?.id ? 'Attach' : disk.createOption || 'Empty'));
        if (disk.caching) lines.push('          caching: ' + quote(disk.caching));
        if (disk.diskSizeGB) lines.push('          diskSizeGB: ' + disk.diskSizeGB);
        if (disk.managedDisk?.id) {
          const diskSym = bicepIdMap[disk.managedDisk.id.toLowerCase()];
          lines.push('          managedDisk: { id: ' + (diskSym ? diskSym + '.id' : quote(disk.managedDisk.id)) + ' }');
        } else if (disk.managedDisk?.storageAccountType) lines.push('          managedDisk: { storageAccountType: ' + quote(disk.managedDisk.storageAccountType) + ' }');
        lines.push('        }');
      });
      lines.push('      ]');
    }
    lines.push('    }');
    if (!attachedOs) {
      lines.push('    osProfile: {');
      lines.push('      computerName: ' + quote(vm.name || 'vm'));
      lines.push('      adminUsername: adminUsername');
      lines.push('      adminPassword: adminPassword');
      lines.push('    }');
    }
    // Network profile
    const nicRefs = vmp.networkProfile?.networkInterfaces || [];
    if (nicRefs.length) {
      lines.push('    networkProfile: {');
      lines.push('      networkInterfaces: [');
      nicRefs.forEach(n => {
        const nicSym = bicepIdMap[(n.id || '').toLowerCase()];
        lines.push('        {');
        if (nicSym) {
          lines.push('          id: ' + nicSym + '.id');
        } else {
          lines.push('          id: ' + quote(n.id));
        }
        const primary = (n.properties || n).primary;
        if (typeof primary === 'boolean') lines.push('          properties: { primary: ' + primary + ' }');
        lines.push('        }');
      });
      lines.push('      ]');
      lines.push('    }');
    }
    lines.push('  }');
    lines.push('}');
    lines.push('');
  });

  // --- Managed Disks ---
  disks.forEach(disk => {
    const sym = diskSymbols.get(disk);
    const dp = disk.properties || disk;
    lines.push('resource ' + sym + ' \'Microsoft.Compute/disks@2023-04-02\' = {');
    lines.push('  name: ' + quote(disk.name || 'disk'));
    lines.push('  location: location');
    lines.push('  sku: {');
    lines.push('    name: ' + quote(dp.accountType || disk.sku?.name || 'Standard_LRS'));
    lines.push('  }');
    _bicepTags(disk, 1);
    lines.push('  properties: {');
    lines.push('    creationData: {');
    lines.push('      createOption: ' + quote(dp.creationData?.createOption || 'Empty'));
    if (dp.creationData?.sourceResourceId) lines.push('      sourceResourceId: ' + quote(dp.creationData.sourceResourceId));
    for (const field of ['sourceUri', 'storageAccountId']) if (dp.creationData?.[field]) lines.push('      ' + field + ': ' + quote(dp.creationData[field]));
    if (dp.creationData?.imageReference?.id) {
      const image = dp.creationData.imageReference;
      lines.push('      imageReference: { id: ' + quote(image.id) + (image.lun != null ? ', lun: ' + image.lun : '') + ' }');
    }
    lines.push('    }');
    if (dp.diskSizeGB) lines.push('    diskSizeGB: ' + dp.diskSizeGB);
    lines.push('  }');
    lines.push('}');
    lines.push('');
  });

  // --- Azure Firewall ---
  firewalls.forEach(fw => {
    const sym = _bsym(fw.name, 'firewall');
    const fwp = fw.properties || {};
    lines.push('resource ' + sym + ' \'Microsoft.Network/azureFirewalls@2023-04-01\' = {');
    lines.push('  name: ' + quote(fw.name || 'firewall'));
    lines.push('  location: location');
    _bicepTags(fw, 1);
    lines.push('  properties: {');
    lines.push('    sku: {');
    lines.push('      name: ' + quote(fw.sku?.name || 'AZFW_VNet'));
    lines.push('      tier: ' + quote(fw.sku?.tier || 'Standard'));
    lines.push('    }');
    const ipConfigs = fwp.ipConfigurations || [];
    if (ipConfigs.length) {
      lines.push('    ipConfigurations: [');
      ipConfigs.forEach(ipc => {
        lines.push('      {');
        lines.push('        name: ' + quote(ipc.name || 'fw-ipconfig'));
        lines.push('        properties: {');
        if (ipc.properties?.subnet?.id) {
          const subSym = bicepIdMap[(ipc.properties.subnet.id || '').toLowerCase()];
          if (subSym) {
            lines.push('          subnet: { id: ' + subSym + '.id }');
          } else {
            lines.push('          subnet: { id: ' + quote(ipc.properties.subnet.id) + ' }');
          }
        }
        if (ipc.properties?.publicIPAddress?.id) {
          lines.push('          publicIPAddress: { id: ' + quote(ipc.properties.publicIPAddress.id) + ' }');
        }
        lines.push('        }');
        lines.push('      }');
      });
      lines.push('    ]');
    }
    lines.push('  }');
    lines.push('}');
    lines.push('');
  });

  // --- Bastion Host ---
  bastions.forEach(bast => {
    const sym = _bsym(bast.name, 'bastion');
    const bp = bast.properties || {};
    lines.push('resource ' + sym + ' \'Microsoft.Network/bastionHosts@2023-04-01\' = {');
    lines.push('  name: ' + quote(bast.name || 'bastion'));
    lines.push('  location: location');
    _bicepTags(bast, 1);
    lines.push('  properties: {');
    const ipConfigs = bp.ipConfigurations || [];
    if (ipConfigs.length) {
      lines.push('    ipConfigurations: [');
      ipConfigs.forEach(ipc => {
        lines.push('      {');
        lines.push('        name: ' + quote(ipc.name || 'bastion-ipconfig'));
        lines.push('        properties: {');
        if (ipc.properties?.subnet?.id) {
          const subSym = bicepIdMap[(ipc.properties.subnet.id || '').toLowerCase()];
          if (subSym) {
            lines.push('          subnet: { id: ' + subSym + '.id }');
          } else {
            lines.push('          subnet: { id: ' + quote(ipc.properties.subnet.id) + ' }');
          }
        }
        if (ipc.properties?.publicIPAddress?.id) {
          lines.push('          publicIPAddress: { id: ' + quote(ipc.properties.publicIPAddress.id) + ' }');
        }
        lines.push('        }');
        lines.push('      }');
      });
      lines.push('    ]');
    }
    lines.push('  }');
    lines.push('}');
    lines.push('');
  });

  // --- Peerings ---
  peerings.forEach(peer => {
    const pp = peer.properties || {};
    const srcVnetId = peer._sourceVnetId || peer.id?.split('/virtualNetworkPeerings/')[0] || '';
    const srcVnetSym = bicepIdMap[srcVnetId.toLowerCase()];
    const sym = _bsym(peer.name, 'peering');
    lines.push('resource ' + sym + ' \'Microsoft.Network/virtualNetworks/virtualNetworkPeerings@2023-04-01\' = {');
    if (srcVnetSym) {
      lines.push('  parent: ' + srcVnetSym);
    }
    lines.push('  name: ' + quote(peer.name || 'peering'));
    lines.push('  properties: {');
    lines.push('    remoteVirtualNetwork: {');
    lines.push('      id: ' + quote(pp.remoteVirtualNetwork?.id));
    lines.push('    }');
    lines.push('    allowVirtualNetworkAccess: ' + (pp.allowVirtualNetworkAccess !== false));
    lines.push('    allowForwardedTraffic: ' + (pp.allowForwardedTraffic === true));
    lines.push('    allowGatewayTransit: ' + (pp.allowGatewayTransit === true));
    lines.push('    useRemoteGateways: ' + (pp.useRemoteGateways === true));
    lines.push('  }');
    lines.push('}');
    lines.push('');
  });

  // --- Outputs ---
  vnets.forEach(vnet => {
    const sym = bicepIdMap[(vnet.id || '').toLowerCase()];
    if (sym) {
      lines.push('output ' + sym + 'Id string = ' + sym + '.id');
    }
  });

  if (vms.length) warnings.push('VM passwords must be provided at deployment. Use Key Vault references for production.');
  if (peerings.length) warnings.push('VNet peering requires both sides. Reverse peerings may need separate config.');

  const code = lines.join('\n');
  return {
    code,
    warnings,
    stats: {
      vnets: vnets.length,
      nsgs: uniqueNsgs.length,
      vms: vms.length,
      total: lines.filter(l => l.match(/^resource /)).length
    }
  };
}
